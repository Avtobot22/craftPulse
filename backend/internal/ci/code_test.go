func writeFiles(t *testing.T, root string, files map[string]string) {
	t.Helper()
	for name, content := range files {
		p := filepath.Join(root, filepath.FromSlash(name))
		require.NoError(t, os.MkdirAll(filepath.Dir(p), 0o750))
		require.NoError(t, os.WriteFile(p, []byte(content), 0o600))
	}
}

func TestGoScope_ExcludesVendorBuildGeneratedAndMarksTests(t *testing.T) {
	root := t.TempDir()
	writeFiles(t, root, map[string]string{
		"svc/go.mod":                      "module example.com/svc\n",
		"svc/main.go":                     "package main\n",
		"svc/main_test.go":                "package main\n",
		"svc/api/api.gen.go":              "// Header.\n\n// Code generated by tool. DO NOT EDIT.\n\npackage api\n",
		"svc/api/api.go":                  "package api\n\n// Code generated by tool. DO NOT EDIT.\n",
		"svc/testdata/case/case.go":       "package c\n",
		"svc/testdata/mod/go.mod":         "module example.com/fixture\n",
		"svc/vendor/example.com/lib/l.go": "package lib\n",
		"svc/build/out.go":                "package build\n",
		"svc/.cache/x.go":                 "package x\n",
		"svc/_old/x.go":                   "package x\n",
		"svc/tools/go.mod":                "module example.com/tools\n",
		"svc/tools/tool.go":               "package tools\n",
		"svc/README.md":                   "not code\n",
		"other/ignored.go":                "package other\n",
	})

	s, err := GoScope(root, "svc")

	require.NoError(t, err)
	assert.Equal(t, []string{"svc/api/api.go", "svc/main.go", "svc/main_test.go", "svc/testdata/case/case.go", "svc/tools/tool.go"}, s.Files)
	assert.Equal(t, []string{"svc/main_test.go", "svc/testdata/case/case.go"}, s.Tests)
	assert.ElementsMatch(t, []envelope.ScanExcludedTarget{
		{Path: "svc/api/api.gen.go", Reason: envelope.ScanExcludedTargetReasonGenerated},
		{Path: "svc/vendor", Reason: envelope.ScanExcludedTargetReasonVendor},
		{Path: "svc/build", Reason: envelope.ScanExcludedTargetReasonBuild},
	}, s.Excluded)
	assert.ElementsMatch(t, []GoModule{{Dir: "svc", Pattern: "./..."}, {Dir: "svc/tools", Pattern: "./..."}}, s.Modules)
	assert.Equal(t, []string{"svc/.cache", "svc/_old"}, s.Hidden)
}

func TestGoScope_ComponentInsideEnclosingModule(t *testing.T) {
	root := t.TempDir()
	writeFiles(t, root, map[string]string{"go.mod": "module example.com/mono\n", "services/billing/b.go": "package billing\n"})

	nested, err := GoScope(root, "services/billing")
	require.NoError(t, err)
	whole, err := GoScope(root, "")
	require.NoError(t, err)

	assert.Equal(t, []GoModule{{Dir: ".", Pattern: "./services/billing/..."}}, nested.Modules)
	assert.Equal(t, []GoModule{{Dir: ".", Pattern: "./..."}}, whole.Modules)
	_, err = GoScope(root, "missing")
	require.Error(t, err)
}

func TestMergeSARIF_JoinsRunsAndRefusesOtherVersions(t *testing.T) {
	dir := t.TempDir()
	writeFiles(t, dir, map[string]string{
		"a.sarif": `{"version":"2.1.0","$schema":"s","runs":[{"tool":{"driver":{"name":"golangci-lint"}},"results":[{"ruleId":"errcheck"}]}]}`,
		"b.sarif": `{"version":"2.1.0","runs":[{"tool":{"driver":{"name":"golangci-lint"}},"results":[]}]}`,
		"c.sarif": `{"version":"2.0.0","runs":[]}`,
	})
	out := filepath.Join(dir, "out.sarif")

	require.NoError(t, mergeSARIF([]string{filepath.Join(dir, "a.sarif"), filepath.Join(dir, "b.sarif")}, out))
	data, err := os.ReadFile(out)
	require.NoError(t, err)
	var merged sarifParts
	require.NoError(t, json.Unmarshal(data, &merged))
	assert.Equal(t, "2.1.0", merged.Version)
	assert.Len(t, merged.Runs, 2)
	got, err := SARIFFindings(data, dir)
	require.NoError(t, err)
	assert.Equal(t, []Finding{{Rule: "errcheck"}}, got)

	require.ErrorContains(t, mergeSARIF([]string{filepath.Join(dir, "c.sarif")}, out), `SARIF version "2.0.0"`)
}

func TestStripClones_KeepsCoordinatesWithoutCode(t *testing.T) {
	dir := t.TempDir()
	src, dst := filepath.Join(dir, "in.json"), filepath.Join(dir, "out.json")
	writeFiles(t, dir, map[string]string{"in.json": `{"duplicates":[{"format":"go","lines":12,"tokens":120,"fragment":"password := \"x\"",
		"firstFile":{"name":"b.go","start":3,"end":14},"secondFile":{"name":"a.go","start":5,"end":16}}],"statistics":{"total":{"clones":1}}}`})

	require.NoError(t, stripClones(src, dst))

	data, err := os.ReadFile(dst)
	require.NoError(t, err)
	assert.NotContains(t, string(data), "fragment")
	assert.NotContains(t, string(data), "password")
	f, err := os.Open(dst)
	require.NoError(t, err)
	defer f.Close()
	facts, err := cloneFacts(f)
	require.NoError(t, err)
	assert.Equal(t, []string{"clone a.go:5-16 b.go:3-14"}, facts)
}

func TestFunctionFacts_ReadsLizardCSV(t *testing.T) {
	csv := `9,3,37,2,9,"F@4-12@svc/x/a.go","svc/x/a.go","F","F a , b int",4,12` + "\n" +
		`1,1,11,0,1,"M@16-16@./svc/x/a.go","./svc/x/a.go","M","(t*T)M",16,16` + "\n"

	facts, err := functionFacts(strings.NewReader(csv))

	require.NoError(t, err)
	assert.Equal(t, []string{"function svc/x/a.go:4 F ccn=3 nloc=9", "function svc/x/a.go:16 M ccn=1 nloc=1"}, facts)
	_, err = functionFacts(strings.NewReader("1,2,3\n"))
	require.Error(t, err)
}

func TestReadExpected_CanonicalFacts(t *testing.T) {
	name := filepath.Join(t.TempDir(), FixtureExpected)
	writeFiles(t, filepath.Dir(name), map[string]string{FixtureExpected: "# comment\nerrcheck ./a.go:7\n" +
		"function ./a.go:3 F ccn=2 nloc=5\nclone z.go:1-10 a.go:2-11\ntest a_test.go\nexcluded vendor vendor\n"})

	findings, facts, err := readExpected(name)

	require.NoError(t, err)
	assert.Equal(t, []Finding{{Rule: "errcheck", File: "a.go", Line: 7}}, findings)
	assert.Equal(t, map[string][]string{
		"function": {"function a.go:3 F ccn=2 nloc=5"}, "clone": {"clone a.go:2-11 z.go:1-10"},
		"test": {"test a_test.go"}, "excluded": {"excluded vendor vendor"},
	}, facts)

	writeFiles(t, filepath.Dir(name), map[string]string{FixtureExpected: "function a.go:3 F ccn=2\n"})
	_, _, err = readExpected(name)
	require.ErrorContains(t, err, "line 1")
}

func TestLoadCodeProfile_GoDefault(t *testing.T) {
	p, err := LoadCodeProfile("profiles/go-default")

	require.NoError(t, err)
	assert.Equal(t, "go-default", p.ID)
	assert.Equal(t, map[string]string{ToolLint: "2.15.0", ToolFunctions: "1.25.0", ToolClones: "5.4.2"}, p.Tools)
	assert.Len(t, p.RulesHash(), 64)

	dir := t.TempDir()
	for _, name := range []string{LintConfigFile, ClonesFile} {
		data, err := os.ReadFile(filepath.Join("profiles", "go-default", name))
		require.NoError(t, err)
		writeFiles(t, dir, map[string]string{name: string(data)})
	}
	writeFiles(t, dir, map[string]string{CodeProfileFile: `{"profile_id":"go-default","language":"python","timeout":"0s","tools":{},"functions":{"ccn_threshold":10,"nloc_threshold":50}}`})
	_, err = LoadCodeProfile(dir)
	require.ErrorContains(t, err, `language "python" is not supported`)
	require.ErrorContains(t, err, "tools.lizard: version is required")
	require.ErrorContains(t, err, "timeout must be a positive duration")
}
