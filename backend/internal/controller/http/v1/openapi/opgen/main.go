package main

import (
	"bytes"
	"cmp"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"slices"
	"strings"

	"go.yaml.in/yaml/v3"
)

var (
	_methods = []string{"get", "put", "post", "delete", "options", "head", "patch", "trace"}
	_param   = regexp.MustCompile(`\{([^}]+)\}`)
)

// operation keeps the key names of the OpenAPI document and its x-craftpulse extension.
type operation struct {
	ID         string      `yaml:"operationId"`         //nolint:tagliatelle // OpenAPI key
	Action     string      `yaml:"x-craftpulse-action"` //nolint:tagliatelle // contract extension key
	Parameters []parameter `yaml:"parameters"`
}

type parameter struct {
	Ref  string `yaml:"$ref"`
	Name string `yaml:"name"`
	In   string `yaml:"in"`
}

type route struct {
	key     string
	op      operation
	query   []string
	ifMatch bool
}

func main() {
	in := flag.String("in", "", "openapi.yaml")
	out := flag.String("out", "", "file to write")
	flag.Parse()
	if err := run(*in, *out); err != nil {
		fmt.Fprintln(os.Stderr, "opgen:", err)
		os.Exit(1)
	}
}

func run(in, out string) error {
	src, err := os.ReadFile(in)
	if err != nil {
		return err
	}
	var doc struct {
		Paths      map[string]map[string]yaml.Node `yaml:"paths"`
		Components struct {
			Parameters map[string]parameter `yaml:"parameters"`
		} `yaml:"components"`
	}
	if err := yaml.Unmarshal(src, &doc); err != nil {
		return fmt.Errorf("parse %s: %w", in, err)
	}
	routes, err := collect(doc.Paths, doc.Components.Parameters)
	if err != nil {
		return err
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by opgen. DO NOT EDIT.\n\npackage openapi\n\n")
	b.WriteString("// Operations maps \"METHOD gin path\" to the contract operation: operationId, x-craftpulse-action,\n")
	b.WriteString("// query parameters and the required If-Match header.\n")
	b.WriteString("var Operations = map[string]Operation{\n")
	for _, r := range routes {
		fmt.Fprintf(&b, "\t%q: {ID: %q, Action: %q, Query: %#v, IfMatch: %t},\n", r.key, r.op.ID, r.op.Action, r.query, r.ifMatch)
	}
	b.WriteString("}\n")
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(out, formatted, 0o600)
}

func collect(paths map[string]map[string]yaml.Node, shared map[string]parameter) ([]route, error) {
	var (
		routes []route
		errs   []error
	)
	for p, item := range paths {
		var common []parameter
		if node, ok := item["parameters"]; ok {
			if err := node.Decode(&common); err != nil {
				return nil, fmt.Errorf("%s parameters: %w", p, err)
			}
		}
		for _, m := range _methods {
			node, ok := item[m]
			if !ok {
				continue
			}
			var op operation
			if err := node.Decode(&op); err != nil {
				return nil, fmt.Errorf("%s %s: %w", m, p, err)
			}
			if op.ID == "" || op.Action == "" {
				errs = append(errs, fmt.Errorf("%s %s has no operationId or x-craftpulse-action", m, p))
				continue
			}
			r := route{key: strings.ToUpper(m) + " " + _param.ReplaceAllString(p, ":$1"), op: op, query: []string{}}
			for _, prm := range append(common, op.Parameters...) {
				if prm.Ref != "" {
					resolved, ok := shared[strings.TrimPrefix(prm.Ref, "#/components/parameters/")]
					if !ok {
						errs = append(errs, fmt.Errorf("%s %s: unknown parameter %s", m, p, prm.Ref))
						continue
					}
					prm = resolved
				}
				switch {
				case prm.In == "query":
					r.query = append(r.query, prm.Name)
				case prm.In == "header" && strings.EqualFold(prm.Name, "If-Match"):
					r.ifMatch = true
				}
			}
			slices.Sort(r.query)
			routes = append(routes, r)
		}
	}
	slices.SortFunc(routes, func(a, b route) int { return cmp.Compare(a.key, b.key) })
	return routes, errors.Join(errs...)
}
