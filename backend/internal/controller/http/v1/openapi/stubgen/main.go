package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
)

var (
	_iface  = regexp.MustCompile(`(?s)type StrictServerInterface interface \{(.*?)\n\}`)
	_method = regexp.MustCompile(`(?m)^\t(\w+)\(ctx context\.Context, request (\w+)\) \((\w+), error\)$`)
)

func main() {
	in := flag.String("in", "", "oapi-codegen output")
	out := flag.String("out", "", "file to write")
	flag.Parse()
	if err := run(*in, *out); err != nil {
		fmt.Fprintln(os.Stderr, "stubgen:", err)
		os.Exit(1)
	}
}

func run(in, out string) error {
	src, err := os.ReadFile(in)
	if err != nil {
		return err
	}
	iface := _iface.FindSubmatch(src)
	if iface == nil {
		return errors.New("StrictServerInterface not found")
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by stubgen. DO NOT EDIT.\n\npackage openapi\n\nimport \"context\"\n\n")
	b.WriteString("type Unimplemented struct{}\n\nvar _ StrictServerInterface = Unimplemented{}\n")
	for _, m := range _method.FindAllSubmatch(iface[1], -1) {
		fmt.Fprintf(&b, "\nfunc (Unimplemented) %s(context.Context, %s) (%s, error) {\n\treturn nil, ErrNotImplemented\n}\n",
			m[1], m[2], m[3])
	}
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(out, formatted, 0o644)
}
