const _goProfile = "../../internal/ci/profiles/go-default"

// The fake tools write the report where the profile asks for it and log their working directory and
// arguments; FAKE_SLEEP delays the linter.
var _fakeTools = map[string]string{
	"golangci-lint": `echo "$PWD $*" >> "$FAKE_LOG/lint.log"
while [ $# -gt 0 ]; do [ "$1" = --output.sarif.path ] && out=$2; shift; done
[ -n "$FAKE_SLEEP" ] && sleep "$FAKE_SLEEP"
printf '%s' '{"version":"2.1.0","runs":[{"tool":{"driver":{"name":"golangci-lint"}},"results":[{"ruleId":"errcheck","locations":[{"physicalLocation":{"artifactLocation":{"uri":"services/billing/main.go"},"region":{"startLine":7}}}]}]}]}' > "$out"
exit 1`,
	"lizard": `while [ $# -gt 0 ]; do case "$1" in -o) out=$2;; -f) cp "$2" "$FAKE_LOG/files.txt";; esac; shift; done
echo '3,1,10,1,3,"Run@5-7@services/billing/main.go","services/billing/main.go","Run","Run name",5,7' > "$out"`,
	"jscpd": `while [ $# -gt 0 ]; do case "$1" in --output) out=$2;; --config) cp "$2" "$FAKE_LOG/jscpd.json";; esac; shift; done
mkdir -p "$out"
printf '%s' '{"duplicates":[{"format":"go","lines":12,"tokens":120,"fragment":"FIXTURE_CODE_FRAGMENT","firstFile":{"name":"services/billing/a.go","start":1,"end":12},"secondFile":{"name":"services/billing/b.go","start":1,"end":12}}],"statistics":{}}' > "$out/jscpd-report.json"`,
}

func fakeCodeTools(t *testing.T) (logDir string) {
	t.Helper()
	bin, logDir := t.TempDir(), t.TempDir()
	for name, script := range _fakeTools {
		require.NoError(t, os.WriteFile(filepath.Join(bin, name), []byte("#!/bin/sh\n"+script+"\n"), 0o700)) //nolint:gosec // a test tool must be executable
	}
	t.Setenv("PATH", bin+string(os.PathListSeparator)+os.Getenv("PATH"))
	t.Setenv("FAKE_LOG", logDir)
	return logDir
}

func codeRepo(t *testing.T, c *cli) string {
	t.Helper()
	repo := c.path("repo")
	for name, content := range map[string]string{
		"services/billing/go.mod":          "module example.com/billing\n",
		"services/billing/main.go":         "package main\n",
		"services/billing/main_test.go":    "package main\n",
		"services/billing/api/api.gen.go":  "// Code generated by fixture. DO NOT EDIT.\n\npackage api\n",
		"services/billing/vendor/lib/l.go": "package lib\n",
		"services/other/other.go":          "package other\n",
	} {
		p := filepath.Join(repo, filepath.FromSlash(name))
		require.NoError(t, os.MkdirAll(filepath.Dir(p), 0o750))
		require.NoError(t, os.WriteFile(p, []byte(content), 0o600))
	}
	c.env["CI_PROJECT_DIR"] = repo
	return repo
}

func fileHash(t *testing.T, names ...string) string {
	t.Helper()
	h := sha256.New()
	for _, name := range names {
		data, err := os.ReadFile(filepath.Join(_goProfile, name))
		require.NoError(t, err)
		h.Write(data)
	}
	return hex.EncodeToString(h.Sum(nil))
}

func TestCode_RecordsThreeToolsWithVersionsScopeAndNoCode(t *testing.T) {
	logs := fakeCodeTools(t)
	api := newFakeAPI(t)
	c := newCLI(t, api)
	repo := codeRepo(t, c)

	out := c.mustRun("code", "--profile-dir", _goProfile)
	c.mustRun("upload", "--dry-run", "--save", c.path("package.tar.gz"))

	assert.Contains(t, out, "tool run go-default-golangci-lint: code builtin by golangci-lint 2.15.0, findings, complete, 1 report(s)")
	assert.Contains(t, out, "tool run go-default-lizard: code builtin by lizard 1.25.0, success, complete, 1 report(s)")
	assert.Contains(t, out, "tool run go-default-jscpd: code builtin by jscpd 5.4.2, success, complete, 1 report(s)")
	lint, err := os.ReadFile(filepath.Join(logs, "lint.log"))
	require.NoError(t, err)
	assert.Contains(t, string(lint), filepath.Join(repo, "services", "billing")+" run --config ")
	assert.Contains(t, string(lint), "--path-prefix services/billing ./...")
	files, err := os.ReadFile(filepath.Join(logs, "files.txt"))
	require.NoError(t, err)
	assert.Equal(t, "services/billing/main.go\nservices/billing/main_test.go\n", string(files))
	config, err := os.ReadFile(filepath.Join(logs, "jscpd.json"))
	require.NoError(t, err)
	assert.Contains(t, string(config), `"pattern":"services/billing/**/*.go"`)
	assert.Contains(t, string(config), `"ignore":["services/billing/api/api.gen.go","services/billing/vendor/**"]`)

	data, err := os.ReadFile(c.path("package.tar.gz"))
	require.NoError(t, err)
	assert.NotContains(t, string(data), "FIXTURE_CODE_FRAGMENT")
	result := checkPackage(t, data)
	require.Len(t, result.ScanManifest.Tools, 3)
	formats := map[string]envelope.ScanReportReportFormat{}
	for _, run := range result.ScanManifest.Tools {
		require.Len(t, run.Reports, 1, run.Id)
		formats[run.Producer] = run.Reports[0].ReportFormat
		assert.Equal(t, "go-default", *run.ProfileId)
		assert.Equal(t, "sha256:6b2f0c1d9e8a7b6c5d4e3f2a1b0c9d8e7f6a5b4c3d2e1f0a9b8c7d6e5f4a3b2c", *run.ProfileImageDigest)
		assert.Equal(t, fileHash(t, "profile.json", "golangci.yml", "jscpd.json"), *run.RulesHash)
		assert.Equal(t, "services/billing", run.Component.PathPrefix)
		assert.Equal(t, []envelope.ScanExcludedTarget{
			{Path: "services/billing/api/api.gen.go", Reason: envelope.ScanExcludedTargetReasonGenerated},
			{Path: "services/billing/vendor", Reason: envelope.ScanExcludedTargetReasonVendor},
		}, *run.ExcludedTargets)
		assert.Equal(t, []string{"services/billing/main_test.go"}, *run.TestTargets)
		assert.Equal(t, 2, *run.ScannedCount)
		assert.Equal(t, envelope.ScanToolRunCompletenessComplete, run.Completeness)
		switch run.Producer {
		case "golangci-lint":
			assert.Equal(t, fileHash(t, "golangci.yml"), *run.ConfigHash)
		case "jscpd":
			assert.Equal(t, fileHash(t, "jscpd.json"), *run.ConfigHash)
		default:
			assert.Nil(t, run.ConfigHash)
		}
	}
	assert.Equal(t, map[string]envelope.ScanReportReportFormat{
		"golangci-lint": envelope.ScanReportReportFormatSarif, "lizard": envelope.ScanReportReportFormatLizardCsv,
		"jscpd": envelope.ScanReportReportFormatJscpdJson,
	}, formats)
}

func TestCode_TimeoutOfProfileGivesTimeoutAndPartial(t *testing.T) {
	fakeCodeTools(t)
	t.Setenv("FAKE_SLEEP", "5")
	c := newCLI(t, newFakeAPI(t))
	codeRepo(t, c)

	out := c.mustRun("code", "--profile-dir", _goProfile, "--timeout", "300ms")
	c.mustRun("upload", "--dry-run", "--save", c.path("package.tar.gz"))

	for _, tool := range []string{"golangci-lint", "lizard", "jscpd"} {
		assert.Contains(t, out, "tool run go-default-"+tool+": code builtin by "+tool)
	}
	data, err := os.ReadFile(c.path("package.tar.gz"))
	require.NoError(t, err)
	for _, run := range checkPackage(t, data).ScanManifest.Tools {
		assert.Equal(t, envelope.ScanToolRunExitClassTimeout, run.ExitClass, run.Id)
		assert.Equal(t, envelope.ScanToolRunCompletenessPartial, run.Completeness, run.Id)
		assert.Empty(t, run.Reports, run.Id)
		assert.Less(t, run.FinishedAt.Sub(run.StartedAt).Seconds(), 4.0, run.Id)
	}
}

