import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import {
  DEFAULT_THEME,
  generateCSS,
  updateBaseColor,
} from '@gravity-ui/uikit-themer'
import { format, resolveConfig } from 'prettier'

const output = new URL('../src/app/styles/theme.css', import.meta.url)
let theme = updateBaseColor({
  theme: DEFAULT_THEME,
  colorToken: 'brand',
  value: { light: '#7c3aed', dark: '#c4b5fd' },
})

// Themer 2.1's default theme shares yellow between brand and warning.
// Bind the new brand palette explicitly so warnings keep their own semantics.
for (const [token, lightShade, darkShade] of [
  ['base-brand', '550-solid', '550-solid'],
  ['base-brand-hover', '600-solid', '650-solid'],
  ['base-selection', '200', '150'],
  ['base-selection-hover', '300', '200'],
  ['line-brand', '550-solid', '550-solid'],
  ['text-brand', '750-solid', '550-solid'],
  ['text-brand-heavy', '750-solid', '550-solid'],
  ['text-link', '750-solid', '550-solid'],
  ['text-link-hover', '850-solid', '650-solid'],
]) {
  for (const [mode, shade] of [
    ['light', lightShade],
    ['dark', darkShade],
  ]) {
    const generated = theme.privateColors.brand?.[mode]?.[shade]
    if (!generated)
      throw new Error(`Missing Gravity brand shade: ${mode}/${shade}`)
    theme.utilityColors[token][mode] = {
      value: generated.value,
      ref: `private.brand.${shade}`,
    }
  }
}

// DS-03/05/08: explicit semantic pairs verified by the contrast table.
const palette = {
  'text-brand-contrast': ['#ffffff', '#1f1633'],
  'text-secondary': ['#4b5563', '#d1d5db'],
  'text-hint': ['#4b5563', '#acb4bf'],
  'text-link-visited': ['#6b21a8', '#e9d5ff'],
  'text-link-visited-hover': ['#581c87', '#f3e8ff'],
  'text-positive': ['#14532d', '#86efac'],
  'text-warning': ['#713f12', '#fde68a'],
  'text-danger': ['#991b1b', '#fda4af'],
  'text-info': ['#1e40af', '#93c5fd'],
  'base-positive-light': ['#eefbf1', '#143321'],
  'base-warning-light': ['#fff4d1', '#3b2c0c'],
  'base-danger-light': ['#fff0f1', '#421b24'],
  'base-info-light': ['#edf3ff', '#172e4a'],
  'line-generic': ['#727780', '#9299a3'],
  'line-generic-solid': ['#727780', '#9299a3'],
  'line-generic-hover': ['#535963', '#b4bac2'],
  'line-generic-active': ['#7c3aed', '#c4b5fd'],
  'line-generic-accent': ['#535963', '#b4bac2'],
  'line-generic-accent-hover': ['#3a404a', '#d1d5db'],
  'line-focus': ['#7c3aed', '#c4b5fd'],
}
for (const [token, [light, dark]] of Object.entries(palette)) {
  theme.utilityColors[token] = {
    light: { value: light },
    dark: { value: dark },
  }
}
for (const kind of ['positive', 'warning', 'danger', 'info']) {
  for (const mode of ['light', 'dark']) {
    theme.utilityColors[`text-${kind}-heavy`][mode] = {
      ...theme.utilityColors[`text-${kind}`][mode],
    }
    theme.utilityColors[`base-${kind}-light-hover`][mode] = {
      ...theme.utilityColors[`base-${kind}-light`][mode],
    }
  }
}
for (const mode of ['light', 'dark']) {
  theme.utilityColors['line-danger'][mode] = {
    ...theme.utilityColors['text-danger'][mode],
  }
  for (const token of ['base-neutral-light', 'base-misc-light'])
    theme.utilityColors[token][mode] = {
      ...theme.utilityColors['base-generic'][mode],
    }
  theme.utilityColors['text-misc-heavy'][mode] = {
    ...theme.utilityColors['text-primary'][mode],
  }
  theme.utilityColors['text-complementary'][mode] = {
    ...theme.utilityColors['text-secondary'][mode],
  }
}

theme.typography.fontFamilies.sans = {
  mainFont: 'Inter',
  fallbackFonts: ['system-ui', 'sans-serif'],
}
theme.typography.fontFamilies.monospace = {
  mainFont: 'ui-monospace',
  fallbackFonts: ['Cascadia Code', 'monospace'],
}
for (const [variant, size, lineHeight] of [
  ['header-1', '1.75rem', '2.25rem'],
  ['header-2', '1.5rem', '2rem'],
  ['subheader-1', '1rem', '1.5rem'],
  ['subheader-3', '1.25rem', '1.75rem'],
  ['body-1', '1rem', '1.5rem'],
  ['body-2', '1rem', '1.5rem'],
  ['body-short', '.875rem', '1.25rem'],
  ['caption-1', '.875rem', '1.25rem'],
  ['code-1', '.875rem', '1.25rem'],
  ['display-1', '2rem', '2.5rem'],
])
  theme.typography.variants[variant] = {
    'font-size': size,
    'line-height': lineHeight,
  }

// Only the brand/semantic deltas are shared with HC. UIKit retains HC surfaces.
const generated = generateCSS({ theme, ignoreDefaultValues: true })
  .replace(
    '.g-root_theme_light {',
    '.g-root_theme_light, .g-root_theme_light-hc {',
  )
  .replace(
    '.g-root_theme_dark {',
    '.g-root_theme_dark, .g-root_theme_dark-hc {',
  )
const css = await format(
  `/* Generated by npm run generate:theme using @gravity-ui/uikit-themer. */\n${generated}`,
  { ...(await resolveConfig(fileURLToPath(output))), parser: 'css' },
)
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')) !== css)
    throw new Error('theme.css is outdated; run npm run generate:theme')
  console.log('Gravity theme matches its generator.')
} else {
  await writeFile(output, css)
}
