export function metricFormula(metricId: string, version: number) {
  return version === 1 && Object.hasOwn(formulas, metricId)
    ? formulas[metricId]
    : undefined
}

export function catalogHref(reference: string) {
  if (
    /^docs\/product\/metrics(?:\.md|\/[a-z0-9-]+\.md)(?:#[^\s]*)?$/u.test(
      reference,
    )
  ) {
    return new URL(
      reference,
      'https://github.com/Avtobot22/craftPulse/blob/main/',
    ).href
  }
  const url = URL.parse(reference)
  return url?.protocol === 'https:' && !url.username && !url.password
    ? url.href
    : undefined
}
